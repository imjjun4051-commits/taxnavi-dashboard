"""prefix 매칭 확장 로직(비교군 15개 미만이면 자릿수 축소) 검증."""
import pandas as pd

from peers import 비교군_찾기, 업종코드_자릿수분포


def 표만들기(코드들):
    return pd.DataFrame([{"corp_code": f"{i:08d}", "corp_name": f"회사{i}",
                          "stock_code": f"{i:06d}", "corp_cls": "K", "induty_code": c}
                         for i, c in enumerate(코드들, 1)])


def test_4자리에서_충분하면_확장없음():
    표 = 표만들기(["2929"] * 20 + ["2830"] * 5)
    비교군, 정보 = 비교군_찾기(표, "2929", 최소개수=15)
    assert len(비교군) == 20
    assert 정보["최종L"] == 4 and 정보["확장여부"] is False


def test_4자리가_부족하면_3자리로_확장():
    # 2929는 10곳뿐이지만 292로 넓히면 18곳
    표 = 표만들기(["2929"] * 10 + ["2921"] * 8 + ["2810"] * 5)
    비교군, 정보 = 비교군_찾기(표, "2929", 최소개수=15)
    assert 정보["최종L"] == 3 and 정보["확장여부"] is True
    assert len(비교군) == 18


def test_2자리까지_넓혀도_부족하면_경고():
    표 = 표만들기(["2929"] * 3 + ["1010"] * 30)
    비교군, 정보 = 비교군_찾기(표, "2929", 최소개수=15)
    assert 정보["최종L"] == 2
    assert 정보["경고"] is not None and "3곳" in 정보["경고"]
    assert len(비교군) == 3


def test_회사코드가_3자리면_3자리로_비교():
    표 = 표만들기(["292"] * 16)
    비교군, 정보 = 비교군_찾기(표, "2929", 최소개수=15)
    assert len(비교군) == 16 and 정보["최종L"] == 3


def test_자릿수분포():
    표 = 표만들기(["2929", "292", "292", ""])
    assert 업종코드_자릿수분포(표) == {0: 1, 3: 2, 4: 1}
