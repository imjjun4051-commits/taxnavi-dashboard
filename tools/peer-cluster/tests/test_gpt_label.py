"""GPT JSON 파싱 실패 시 대체 라벨(A/B/C) 검증."""
from gpt_label import 대체라벨, _형식확인


def 군요약샘플():
    return [{"군번호": 2, "기업수": 5, "특성통계": {}, "매출상위기업": []},
            {"군번호": 0, "기업수": 7, "특성통계": {}, "매출상위기업": []},
            {"군번호": 1, "기업수": 6, "특성통계": {}, "매출상위기업": []}]


def test_대체라벨은_군번호순으로_ABC를_하나씩_준다():
    결과 = 대체라벨(군요약샘플(), "테스트")
    라벨들 = [g["라벨"] for g in 결과["군"]]
    번호들 = [g["군번호"] for g in 결과["군"]]
    assert 라벨들 == ["A", "B", "C"]
    assert 번호들 == [0, 1, 2]          # 군번호 순으로 정렬되어야 한다
    assert 결과["실패"] is True and "테스트" in 결과["실패사유"]


def test_형식확인_라벨중복이면_거부():
    나쁜응답 = {"군": [{"군번호": 0, "라벨": "A", "이름": "x", "핵심기준": "x", "특징요약": "x"},
                     {"군번호": 1, "라벨": "A", "이름": "x", "핵심기준": "x", "특징요약": "x"},
                     {"군번호": 2, "라벨": "C", "이름": "x", "핵심기준": "x", "특징요약": "x"}]}
    assert _형식확인(나쁜응답, 군요약샘플()) is False


def test_형식확인_정상응답은_통과():
    좋은응답 = {"군": [{"군번호": i, "라벨": l, "이름": "x", "핵심기준": "x", "특징요약": "x"}
                     for i, l in enumerate(["A", "B", "C"])]}
    assert _형식확인(좋은응답, 군요약샘플()) is True


def test_형식확인_군개수가_다르면_거부():
    assert _형식확인({"군": []}, 군요약샘플()) is False
