"""K-means 배정 검증 — 기준 기업이 실제로 가장 가까운 중심의 군에 들어가는지."""
import numpy as np
import pandas as pd

from cluster import 군집화, 기준기업_배정
from features import 전처리, 필수특성


def 가짜비교군():
    """규모·성장이 뚜렷하게 다른 3덩어리를 만든다(군이 잘 갈라지도록)."""
    행들 = []
    설계 = [(9.0, 0.20, 0.10, 0.20), (10.5, 0.03, 0.06, 0.03), (9.5, -0.05, 0.00, -0.05)]
    for gi, (lg, 성장, 이익, cagr) in enumerate(설계):
        for i in range(8):
            행들.append({
                "corp_code": f"{gi}{i:04d}", "corp_name": f"회사{gi}{i}",
                "log매출액": lg + i * 0.01, "매출성장률": 성장 + i * 0.001,
                "영업이익률": 이익 + i * 0.001, "매출CAGR3": cagr + i * 0.001,
                "매출액": 10 ** (lg + i * 0.01),
            })
    return pd.DataFrame(행들)


def test_기준기업은_가장_가까운_중심에_배정된다():
    비교군 = 가짜비교군()
    잘린표, X, 스케일러, _ = 전처리(비교군, 필수특성)
    군배정, 모델, 메타 = 군집화(잘린표, X, 필수특성)

    # 고성장 소형(첫 덩어리)과 똑같은 값을 넣으면 그 군에 들어가야 한다
    기준특성 = {"log매출액": 9.0, "매출성장률": 0.20, "영업이익률": 0.10, "매출CAGR3": 0.20}
    배정 = 기준기업_배정(기준특성, 필수특성, 스케일러, 모델)

    같은군 = 군배정[군배정["corp_code"].str.startswith("0")]["군번호"].iloc[0]
    assert 배정["소속군"] == 같은군
    # 1순위 거리가 2순위보다 작아야 한다
    assert 배정["1순위거리"] < 배정["2순위거리"]


def test_군은_항상_3개이고_실루엣이_계산된다():
    비교군 = 가짜비교군()
    잘린표, X, _, _ = 전처리(비교군, 필수특성)
    군배정, 모델, 메타 = 군집화(잘린표, X, 필수특성)
    assert sorted(군배정["군번호"].unique().tolist()) == [0, 1, 2]
    assert 메타["실루엣"] is not None and 0 <= 메타["실루엣"] <= 1


def test_전처리는_결측행을_제외하고_사유를_남긴다():
    비교군 = 가짜비교군()
    비교군.loc[0, "영업이익률"] = np.nan
    잘린표, X, _, 제외 = 전처리(비교군, 필수특성)
    assert len(잘린표) == len(비교군) - 1
    assert len(제외) == 1 and "결측" in 제외.iloc[0]["사유"]
