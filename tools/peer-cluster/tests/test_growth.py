"""성장/정체/감소 판정 규칙의 경계값 검증."""
from growth import 판정


def test_성장_경계값_정확히_충족():
    # 3년 CAGR 5% 이상 '이고' 증가 비율 60% 이상
    assert 판정(0.05, 0.60) == "성장"


def test_성장_조건_하나만_충족하면_성장아님():
    assert 판정(0.05, 0.55) == "정체"     # 비율 미달
    assert 판정(0.04, 0.80) == "정체"     # CAGR 미달


def test_감소_경계값():
    assert 판정(-0.05, 0.80) == "감소"    # CAGR 조건만 충족해도 감소
    assert 판정(0.10, 0.40) == "감소"     # 증가 비율 조건만 충족해도 감소


def test_정체_구간():
    assert 판정(0.0, 0.50) == "정체"
    assert 판정(0.049, 0.99) == "정체"


def test_값이_없으면_판정불가():
    assert 판정(None, 0.7) == "판정 불가"
    assert 판정(0.1, None) == "판정 불가"
