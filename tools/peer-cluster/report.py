"""마크다운 리포트 조립 (reports/peer-cluster_{회사명}_{YYYYMMDD}.md)."""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import pandas as pd

프로젝트루트 = Path(__file__).resolve().parent.parent.parent
리포트폴더 = 프로젝트루트 / "reports"
오렌지, 회색 = "#FF6000", "#6B7583"     # STEERING.md 디자인 토큰(다른 색 추가 금지)


def 억원(값) -> str:
    """원 단위 금액 -> '12.3억원'. 값이 없으면 '-'."""
    if 값 is None or (isinstance(값, float) and pd.isna(값)):
        return "-"
    return f"{float(값) / 1e8:,.1f}억원"


def 퍼센트(값) -> str:
    """비율(0.123) -> '12.3%'. 값이 없으면 '-'."""
    if 값 is None or (isinstance(값, float) and pd.isna(값)):
        return "-"
    return f"{float(값) * 100:,.1f}%"


def _표(제목행: list[str], 행들: list[list[str]]) -> str:
    """마크다운 표 문자열을 만든다."""
    if not 행들:
        return "_해당 데이터가 없습니다._\n"
    머리 = "| " + " | ".join(제목행) + " |"
    구분 = "|" + "|".join(["---"] * len(제목행)) + "|"
    본문 = "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in 행들)
    return f"{머리}\n{구분}\n{본문}\n"


def 상자그림(성장지표: pd.DataFrame, 라벨맵: dict, 저장경로: Path) -> bool:
    """군별 3년 CAGR 상자그림 1장을 그린다(matplotlib 없으면 건너뛴다)."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib import font_manager
    except ImportError:
        return False
    # 한글 글꼴이 있으면 한국어 라벨, 없으면 깨짐 방지를 위해 영어 라벨을 쓴다
    설치된 = {f.name for f in font_manager.fontManager.ttflist}
    한글글꼴 = next((n for n in ("AppleGothic", "Malgun Gothic", "NanumGothic",
                                "Noto Sans CJK KR", "AppleSDGothicNeo-Regular") if n in 설치된), None)
    if 한글글꼴:
        plt.rcParams["font.family"] = 한글글꼴
        plt.rcParams["axes.unicode_minus"] = False
    제목 = "군별 3년 매출 성장률 분포" if 한글글꼴 else "3-year revenue CAGR by cluster"
    y축 = "3년 매출 CAGR (%)" if 한글글꼴 else "3-year revenue CAGR (%)"
    자료, 이름들 = [], []
    for 군, 그룹 in 성장지표.groupby("군번호"):
        값 = 그룹["CAGR3"].dropna() * 100
        if not 값.empty:
            자료.append(값.tolist())
            라벨 = 라벨맵.get(int(군), {}).get("라벨", 군)
            이름들.append(f"{라벨}군" if 한글글꼴 else f"{라벨}")
    if not 자료:
        return False
    fig, ax = plt.subplots(figsize=(6, 3.4), dpi=140)
    상자 = ax.boxplot(자료, labels=이름들, patch_artist=True)
    for p in 상자["boxes"]:
        p.set(facecolor=오렌지, alpha=0.35, edgecolor=오렌지)
    for k in ("whiskers", "caps", "medians"):
        for p in 상자[k]:
            p.set(color=회색)
    ax.axhline(0, color=회색, linewidth=1)
    ax.set_ylabel(y축)
    ax.set_title(제목)
    ax.grid(axis="y", color=회색, alpha=0.2)
    fig.tight_layout()
    저장경로.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(저장경로)
    plt.close(fig)
    return True


def 리포트작성(맥락: dict) -> Path:
    """모든 분석 결과(맥락 딕셔너리)를 받아 마크다운 리포트 파일로 저장한다."""
    t = 맥락["target"]
    회사명 = t.get("회사명", "기준기업")
    오늘 = datetime.now()
    라벨맵 = {g["군번호"]: g for g in 맥락["라벨"]["군"]}
    소속군 = 맥락["배정"]["소속군"]
    소속라벨 = 라벨맵.get(소속군, {}).get("라벨", str(소속군))

    줄 = [f"# 동종 상장기업 비교군 분석 — {회사명}", ""]

    # 1) 개요
    피 = 맥락["peers"]
    매칭 = 맥락["매칭정보"]
    줄 += ["## 1. 개요", "", _표(["항목", "내용"], [
        ["기준 기업", 회사명],
        ["업종코드(KSIC)", f"{t.get('업종코드')} (입력값)"],
        ["매칭 단계 L", f"{매칭['최종L']}자리" + (f" — {매칭['시작L']}자리에서 확장" if 매칭["확장여부"] else " — 확장 없음")],
        ["비교군 수", f"총 {len(피)}곳 (코스닥 {int((피['시장'] == '코스닥').sum())} · 코넥스 {int((피['시장'] == '코넥스').sum())})"],
        ["분석에 쓴 회사 수", f"{len(맥락['군배정'])}곳 (특성 결측 {len(맥락['특성제외'])}곳 제외)"],
        ["기준연도 / 최신 사업연도", f"{맥락['기준연도']}년 / {맥락.get('최신사업연도', '-')}년"],
        ["사용한 특성", ", ".join(맥락["특성목록"]) + f" ({맥락['특성설명']})"],
        ["데이터 기준일", 오늘.strftime("%Y-%m-%d %H:%M")],
    ])]
    if 매칭.get("경고"):
        줄 += [f"> ⚠ {매칭['경고']}", ""]

    # 2) 비교군 표 (군별 정렬)
    줄 += ["## 2. 비교군 (코스닥·코넥스 동종 상장기업)", ""]
    군배정 = 맥락["군배정"].copy()
    군배정["라벨"] = 군배정["군번호"].map(lambda g: 라벨맵.get(int(g), {}).get("라벨", g))
    행들 = [[
        r["라벨"], r["corp_name"], r.get("시장", "-"), r.get("stock_code", "-"),
        억원(r.get("매출액")), 퍼센트(r.get("매출성장률")),
        퍼센트(r.get("영업이익률")), 퍼센트(r.get("매출CAGR3")),
    ] for _, r in 군배정.sort_values(["라벨", "매출액"], ascending=[True, False]).iterrows()]
    줄 += [_표(["군", "회사명", "시장", "종목코드", "매출액", "매출성장률", "영업이익률", "3년 CAGR"], 행들)]

    # 3) 분류 기준 표 (비교군 표 바로 아래)
    줄 += ["## 3. 군 분류 기준 (GPT 작성)", ""]
    기준행 = [[
        g["라벨"], g["이름"],
        int((군배정["군번호"] == g["군번호"]).sum()),
        g["핵심기준"], g["특징요약"],
    ] for g in sorted(맥락["라벨"]["군"], key=lambda x: x["라벨"])]
    줄 += [_표(["군", "군 이름", "기업 수", "핵심 기준", "특징 요약"], 기준행)]
    줄 += ["", f"**분류 기준 설명:** {맥락['라벨'].get('분류기준_설명', '-')}", ""]
    실루엣 = 맥락["군집메타"].get("실루엣")
    줄 += [f"- 실루엣 점수: **{실루엣:.3f}**" if 실루엣 is not None else "- 실루엣 점수: 계산 불가"]
    if 맥락["군집메타"].get("약한군집"):
        줄 += ["- ⚠ 실루엣 점수가 0.25 미만이라 **군 구분이 약합니다**(군 사이 경계가 뚜렷하지 않음)."]
    if 맥락["라벨"].get("실패"):
        줄 += [f"- ⚠ **GPT 라벨 실패** — {맥락['라벨'].get('실패사유', '')}. 군 번호 순서로 임시 배정했습니다."]
    줄 += [""]

    # 4) 기준 기업 판정
    배정 = 맥락["배정"]
    줄 += ["## 4. 기준 기업 판정", "",
           f"**{회사명}**은(는) **{소속라벨}군 ({라벨맵.get(소속군, {}).get('이름', '-')})**에 속합니다."
           f" (2순위: {라벨맵.get(배정['차순위군'], {}).get('라벨', 배정['차순위군'])}군)", ""]
    거리행 = [[라벨맵.get(g, {}).get("라벨", g), 라벨맵.get(g, {}).get("이름", "-"), f"{d:.3f}",
              "← 소속" if g == 소속군 else ("2순위" if g == 배정["차순위군"] else "")]
             for g, d in sorted(배정["거리"].items(), key=lambda x: x[1])]
    줄 += [_표(["군", "군 이름", "중심까지 거리", "비고"], 거리행)]

    기준특성 = 맥락["기준특성"]
    같은군 = 군배정[군배정["군번호"] == 소속군]
    비교행 = []
    for 특성 in 맥락["특성목록"]:
        중위 = 같은군[특성].dropna().median() if 특성 in 같은군 else None
        보기 = (lambda v: f"{v:,.2f}") if 특성 == "log매출액" else 퍼센트
        비교행.append([특성, 보기(기준특성.get(특성)), 보기(None if pd.isna(중위) else 중위)])
    줄 += ["", "### 기준 기업 vs 소속 군 중위값", "", _표(["특성", 회사명, f"{소속라벨}군 중위값"], 비교행)]

    # 5) 군별 매출 성장 분석
    줄 += ["## 5. 군별 과거 매출 성장 분석", ""]
    성장 = 맥락["성장요약"]
    성장행 = [[
        라벨맵.get(int(r["군번호"]), {}).get("라벨", r["군번호"]), int(r["기업수"]),
        퍼센트(r["CAGR5중위"]), 퍼센트(r["CAGR3중위"]), 퍼센트(r["최근1년중위"]),
        퍼센트(r["증가비율_3년"]), 퍼센트(r["증가비율_최근1년"]), r["판정"],
    ] for _, r in 성장.iterrows()]
    줄 += [_표(["군", "기업 수", "5년 CAGR(중위)", "3년 CAGR(중위)", "최근 1년(중위)",
               "3년 증가 비율", "최근 1년 증가 비율", "판정"], 성장행)]
    줄 += ["", "> 판정 규칙: 3년 CAGR 중위값 ≥ +5% **이고** 3년 증가 기업 비율 ≥ 60% → **성장** / "
           "3년 CAGR 중위값 ≤ −5% **또는** 증가 기업 비율 ≤ 40% → **감소** / 그 밖 → **정체**", ""]

    내군 = 성장[성장["군번호"] == 소속군]
    백분위 = 맥락["백분위"]
    if not 내군.empty:
        r = 내군.iloc[0]
        문장 = (f"우리 회사가 속한 **{소속라벨}군**({라벨맵.get(소속군, {}).get('이름', '-')}, {int(r['기업수'])}곳)은 "
                f"최근 3년 매출이 연평균 **{퍼센트(r['CAGR3중위'])}** 성장했고, "
                f"기업의 **{퍼센트(r['증가비율_3년'])}**가 3년 전보다 매출이 늘었습니다. → 판정: **{r['판정']}**")
        c3 = 백분위.get("CAGR3순위")
        if c3:
            문장 += (f"\n\n우리 회사의 3년 CAGR **{퍼센트(기준특성.get('매출CAGR3'))}**는 "
                     f"{소속라벨}군 기업들과 함께 놓았을 때 **{c3['모수']}곳 중 {c3['순위']}위**"
                     f"(상위 {c3['상위퍼센트']:.0f}%)입니다.")
        r1 = 백분위.get("최근1년순위")
        if r1:
            문장 += (f" 최근 1년 성장률 **{퍼센트(기준특성.get('매출성장률'))}**는 "
                     f"**{r1['모수']}곳 중 {r1['순위']}위**(상위 {r1['상위퍼센트']:.0f}%)입니다.")
        줄 += [문장, ""]
    if 맥락.get("그림경로"):
        줄 += [f"![군별 3년 CAGR 분포]({맥락['그림경로']})", ""]

    # 6) 최근 공시
    공시 = 맥락["공시"]
    줄 += ["## 6. 소속 군 최근 12개월 공시", ""]
    if 공시.empty:
        줄 += ["_공시 데이터가 없습니다._", ""]
    else:
        줄 += ["### 공시 유형별 건수", "",
               _표(["공시유형", "건수"], 맥락["공시유형"].values.tolist())]
        주의표 = 공시[공시["주의"] == "주의"]
        줄 += ["", f"### ⚠ 주의 공시 ({len(주의표)}건)", ""]
        줄 += [_표(["접수일", "회사명", "공시명", "제출인", "링크"],
                  [[r["접수일"], r["회사명"], r["공시명"], r["제출인"], f"[열기]({r['링크']})"]
                   for _, r in 주의표.head(30).iterrows()])]
        줄 += ["", "### 최근 공시 30건", "",
               _표(["접수일", "회사명", "공시명", "제출인", "링크"],
                  [[r["접수일"], r["회사명"], r["공시명"], r["제출인"], f"[열기]({r['링크']})"]
                   for _, r in 공시.head(30).iterrows()])]

    # 7) 방법론·한계·면책
    줄 += ["## 7. 방법론 · 한계 · 면책", ""]
    분포 = 맥락.get("자릿수분포", {})
    줄 += [
        "**분석 절차**", "",
        "1. DART 전체 기업 목록에서 상장사를 뽑고, 기업개황으로 코스닥(K)·코넥스(N)만 남깁니다.",
        f"2. 기준 업종코드와 앞자리가 같은 회사를 고릅니다(최종 비교 자릿수 L={매칭['최종L']}). "
        f"15곳이 안 되면 자릿수를 줄여 범위를 넓힙니다.",
        "3. 최근 5개 사업연도 주요계정을 모아 연결(CFS) 우선, 없으면 개별(OFS)을 씁니다.",
        "4. 특성을 1~99 백분위로 윈저라이징하고 표준화한 뒤 K-means(k=3, random_state=42)로 나눕니다.",
        "5. 기준 기업은 학습에 넣지 않고, 같은 스케일로 변환해 가장 가까운 군에 배정합니다.",
        "6. GPT는 군 이름·기준 서술만 담당합니다(**군 소속은 GPT가 정하지 않습니다**).", "",
        "**한계**", "",
        f"- DART의 induty_code 자릿수 분포: {분포 if 분포 else '측정값 없음'} "
        "— 소분류(3자리)까지만 제공되는 회사가 많아 세분류(4자리) 매칭이 항상 되지는 않습니다.",
        "- 연결/개별 재무제표가 회사마다 섞여 있어 규모 비교에 오차가 생길 수 있습니다.",
        "- 코넥스는 재무 항목 누락이 잦아 일부 회사가 분석에서 빠집니다.",
        "- 사업보고서는 결산 후 공시되므로 기준연도 자료가 아직 없는 회사가 있습니다(직전 연도를 최신으로 사용).",
        "- K-means와 GPT는 실행마다 결과가 달라질 수 있어 random_state=42·temperature=0으로 고정했습니다.",
        "- 상장기업 비교군이므로 비상장 중소기업의 평균과는 성격이 다릅니다.", "",
        f"**API 호출 수(이번 실행 누적):** {맥락.get('호출수', '-')}건", "",
        "> 이 리포트는 **참고용이며 투자 권유가 아닙니다.** 출처: 금융감독원 전자공시시스템(DART).", "",
    ]

    리포트폴더.mkdir(parents=True, exist_ok=True)
    파일 = 리포트폴더 / f"peer-cluster_{회사명}_{오늘:%Y%m%d}.md"
    파일.write_text("\n".join(줄), encoding="utf-8")
    return 파일
